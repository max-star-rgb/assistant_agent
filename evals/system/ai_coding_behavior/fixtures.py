_MAX_GIT_OUTPUT_BYTES = 65_536
_DIRECTORY_FLAGS = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC
_MAX_CLEANUP_ENTRIES = 4096
_MAX_CLEANUP_FILES = 2048
_MAX_CLEANUP_DEPTH = 32
_MAX_CLEANUP_BYTES = 64 * 1024 * 1024
_MAX_FIXTURE_SLOTS = 32


@dataclass(frozen=True, slots=True)
class _FixtureDefinition:
    files: Mapping[str, str]
    forbidden_paths: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class CodingBehaviorFixture:
    case_id: str
    fixture_id: str
    repository: Path
    base_commit: str
    base_tree_digest: str
    forbidden_entry_digests: tuple[tuple[str, str], ...]
    held_out_command_id: str
    case_binding_digest: str
    capability_token: str


@dataclass(slots=True)
class _OwnedFixture:
    fixture: CodingBehaviorFixture
    repository_name: str
    repository_device: int
    repository_inode: int
    cleanup_identity_drift: bool = False
    state: Literal["initializing", "active", "cleanup_pending"] = "initializing"
    cleanup_inventory: tuple["_CleanupInventoryEntry", ...] | None = None


class _CleanupIdentityDrift(RuntimeError):
    pass


@dataclass(slots=True)
class _CleanupBudget:
    entries: int = 0
    files: int = 0
    bytes: int = 0


@dataclass(frozen=True, order=True, slots=True)
class _CleanupInventoryEntry:
    relative_path: str
    entry_type: Literal["directory", "regular"]
    device: int
    inode: int
    mode: int
    link_count: int
    size: int


class FixtureCreationError(ValueError):
    """Initialization failed after a bounded cleanup capability was registered."""

    def __init__(self, fixture: CodingBehaviorFixture) -> None:
        super().__init__("fixture initialization failed with cleanup pending")
        self.fixture = fixture


def _cleanup_mutation_hook(parent_fd: int, name: str) -> None:
    """Test seam immediately before a cleanup namespace mutation."""


class FixtureLease:
    """Short-lived descriptor lease for one exact root/repository incarnation."""

    __slots__ = ("_store", "_record", "root_fd", "repository_fd", "_closed")

    def __init__(
        self,
        store: "CodingBehaviorFixtureStore",
        record: _OwnedFixture,
        root_fd: int,
        repository_fd: int,
    ) -> None:
        self._store = store
        self._record = record
        self.root_fd = root_fd
        self.repository_fd = repository_fd
        self._closed = False

    @property
    def repository(self) -> Path:
        return Path(f"/proc/self/fd/{self.repository_fd}")

    @property
    def repository_inode(self) -> int:
        return self._record.repository_inode

    @property
    def pass_fds(self) -> tuple[int, ...]:
        return (self.repository_fd,)

    def validate(self) -> None:
        if self._closed:
            raise ValueError("fixture lease is closed")
        self._store._validate_lease(self)

    def close(self) -> None:
        if self._closed:
            return
        self._closed = True
        os.close(self.repository_fd)
        os.close(self.root_fd)

    def __enter__(self) -> "FixtureLease":
        self.validate()
        return self

    def __exit__(self, *exc_info: object) -> None:
        self.close()

    def __del__(self) -> None:
        try:
            self.close()
        except OSError:
            pass


